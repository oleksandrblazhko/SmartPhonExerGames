# pip install spacy

import spacy

# 🔹 Завантаження мовної моделі spaCy
# Вона містить:
# - токенізацію (розбиття тексту на слова)
# - POS-tagging (визначення частин мови)
# - dependency parsing (синтаксичні зв’язки)
nlp = spacy.load("en_core_web_sm")

# 🔹 Вхідний текст
text = "The wolf eats meat in the forest."

# 🔹 Аналіз тексту spaCy
# На цьому етапі будується dependency tree
doc = nlp(text)

# 🔹 Список для збереження результатів (триплетів)
triples = []

# =========================================================
# 🔹 ЕТАП 1: Пошук дієслів як центрів подій
# =========================================================
for token in doc:

    # ✔️ Нас цікавлять тільки дієслова
    # бо вони є "ядром" відношення (predicate)
    if token.pos_ == "VERB":

        subject = None   # хто виконує дію
        obj = None       # що є прямим об’єктом дії

        # =====================================================
        # 🔹 ЕТАП 2: Пошук підмета (subject)
        # =====================================================
        # nsubj = nominal subject
        # (хто виконує дію)
        for child in token.children:
            if child.dep_ == "nsubj":
                subject = child.lemma_  # нормалізуємо слово (wolf, wolves → wolf)

        # =====================================================
        # 🔹 ЕТАП 3: Пошук прямого об’єкта (direct object)
        # =====================================================
        # dobj / obj = над чим виконується дія
        for child in token.children:
            if child.dep_ in ("dobj", "obj"):
                obj = child.lemma_

        # =====================================================
        # 🔹 ЕТАП 4: Додаємо базовий SVO триплет
        # =====================================================
        if subject and obj:
            triples.append((subject, token.lemma_, obj))

        # =====================================================
        # 🔹 ЕТАП 5: Обробка прийменникових конструкцій
        # =====================================================
        # Приклад: "in the forest"
        #
        # in → prep (прийменник)
        # forest → pobj (об’єкт прийменника)
        #
        # Це НЕ прямий об’єкт дії, а контекст (місце)
        for child in token.children:
            if child.dep_ == "prep":  # знайдено прийменник (in)

                prep = child.lemma_  # "in", "on", "at" тощо

                # шукаємо об’єкт прийменника (pobj)
                for subchild in child.children:
                    if subchild.dep_ == "pobj":

                        # =================================================
                        # 🔹 ЕТАП 6: Семантичне перетворення прийменника
                        # =================================================
                        # Ми перетворюємо синтаксис → семантику
                        relation_map = {
                            "in": "located_in",
                            "on": "located_on",
                            "at": "located_at"
                        }

                        # якщо немає в мапі → залишаємо як є
                        relation = relation_map.get(prep, prep)

                        # формуємо семантичний триплет
                        triples.append(
                            (subject, relation, subchild.lemma_)
                        )

# =========================================================
# 🔹 Вивід результату
# =========================================================
print(triples)